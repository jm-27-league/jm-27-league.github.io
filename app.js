function team(id) { return teamIndex.get(id) || { abbr: "?", nick: "Unknown", city: "", division: "" }; }

function record(teamId) {
  const s = (DATA.standings || []).find((r) => r.teamId === teamId);
  if (!s) return "";
  return s.ties ? `${s.wins}-${s.losses}-${s.ties}` : `${s.wins}-${s.losses}`;
}

/* ---------- Tiny DOM helpers ---------- */

function el(tag, cls, text) {
  const node = document.createElement(tag);
  if (cls) node.className = cls;
  if (text !== undefined) node.textContent = text;
  return node;
}

function svgIcon(path, cls) {
  const s = document.createElementNS("http://www.w3.org/2000/svg", "svg");
  s.setAttribute("viewBox", "0 0 24 24");
  if (cls) s.setAttribute("class", cls);
  const p = document.createElementNS("http://www.w3.org/2000/svg", "path");
  p.setAttribute("d", path);
  s.appendChild(p);
  return s;
}

function logoImg(abbr, cls) {
  const img = el("img", cls || "logo");
  img.src = logoUrl(abbr);
  img.alt = abbr;
  img.loading = "lazy";
  img.onerror = () => { img.style.visibility = "hidden"; };
  return img;
}

function avatar(row, sizeCls) {
  const ring = teamColor(team(row.teamId).abbr);
  if (row.portraitId) {
    const img = el("img", "avatar " + (sizeCls || ""));
    img.style.setProperty("--ring", ring);
    img.src = portraitUrl(row.portraitId);
    img.alt = row.name;
    img.loading = "lazy";
    img.onerror = () => img.replaceWith(initialsAvatar(row, ring, sizeCls));
    return img;
  }
  return initialsAvatar(row, ring, sizeCls);
}

function initialsAvatar(row, ring, sizeCls) {
  const d = el("div", "avatar initials " + (sizeCls || ""));
  d.style.setProperty("--ring", ring);
  d.textContent = row.name.split(" ").map((w) => w[0] || "").join("").slice(0, 2).toUpperCase();
  return d;
}

function sectionHead(title, sub) {
  const head = el("div", "section-head");
  head.appendChild(el("div", "section-title", title));
  if (sub) head.appendChild(el("div", "section-sub", sub));
  return head;
}

function timeAgo(iso) {
  const mins = Math.max(1, Math.round((Date.now() - new Date(iso).getTime()) / 60000));
  if (mins < 60) return `${mins}m`;
  const hrs = Math.round(mins / 60);
  if (hrs < 24) return `${hrs}h`;
  return `${Math.round(hrs / 24)}d`;
}

