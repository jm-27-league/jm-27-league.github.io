/* ---------- Trade builder ----------
   Builds a trade from the rosters already in site.json and encodes it as an
   `FO1.` code — the SAME format src/discord/tradeCode.ts decodes. No server:
   the code is pasted into Discord (/trade import), and Discord supplies the
   identity. Pick values mirror src/discord/draftPickValue.ts's constants. */

const TRADE = {
  a: null, b: null,           // teamIds
  aPlayers: [], bPlayers: [], // rosterIds
  aPicks: [], bPicks: [],     // [round, slotOrNull, yearOffset]
  code: null,                 // generated code, cleared on any edit
};
const tradeSearchQ = { a: "", b: "" }; // transient per-side roster filter, survives re-renders but not reloads

function tradeSaveState() {
  try { localStorage.setItem("trade-draft", JSON.stringify(TRADE)); } catch {}
}
function tradeLoadState() {
  try {
    const saved = JSON.parse(localStorage.getItem("trade-draft") || "null");
    if (saved && typeof saved === "object") Object.assign(TRADE, saved, { code: null });
  } catch {}
}
tradeLoadState();

function base64url(str) {
  return btoa(String.fromCharCode(...new TextEncoder().encode(str)))
    .replaceAll("+", "-").replaceAll("/", "_").replace(/=+$/, "");
}

function buildTradeCode() {
  return "FO1." + base64url(JSON.stringify([TRADE.a, TRADE.b, TRADE.aPlayers, TRADE.bPlayers, TRADE.aPicks, TRADE.bPicks]));
}

/* Mirrors computeDraftPickValue in draftPickValue.ts — keep the constants in sync. */
function pickValue(round, slot, yearOffset) {
  const perRound = DATA.picksPerRound || 32;
  const s = Math.min(Math.max(slot == null ? Math.ceil(perRound / 2) : slot, 1), perRound);
  const overall = (round - 1) * perRound + s;
  return Math.round(650 * Math.pow(0.97, overall - 1) * Math.pow(0.85, yearOffset));
}

const YEAR_WORDS = ["this year", "next year", "year after"];
/* A pick's draft by year: 2028/2029/2030 while the league's next draft is 2028
   (DATA.nextDraftYear, from EA's calendar — see src/discord/draftYear.ts), so the labels
   move on with the league each season. An older site.json without it keeps the words. */
function draftYearWord(offset) {
  return DATA && DATA.nextDraftYear ? String(DATA.nextDraftYear + offset) : YEAR_WORDS[offset];
}
function draftYearOption(offset) {
  const w = draftYearWord(offset);
  return DATA && DATA.nextDraftYear ? `${w} draft` : w[0].toUpperCase() + w.slice(1);
}
function pickChipLabel(p) {
  const [round, slot, yr] = p;
  return pickText(round, slot, draftYearWord(yr));
}
/* "1st rd (1.05) · 2028": a pick as the builder's chips and the trade queue both show it. */
function pickText(round, slot, year) {
  return `${round}${["st","nd","rd"][round-1] || "th"} rd${slot ? ` (${round}.${String(slot).padStart(2,"0")})` : ""} · ${year}`;
}

/* Where a player is now, for explaining why he left a saved trade. */
function whereNow(id) {
  for (const [key, roster] of Object.entries(DATA.rosters || {})) {
    const p = roster.find((r) => r.id === id);
    if (p) return `${p.name}, now with the ${team(Number(key)).nick}`;
  }
  const fa = (DATA.freeAgents || []).find((r) => r.id === id);
  return fa ? `${fa.name}, now a free agent` : null;
}

/* A saved draft outlives the league moving on, so it's squared with the current data
   before it's shown or encoded:
   - a player traded or released since it was saved isn't in that roster any more, so
     his chip never renders, yet he still rode in the code and the bot rejected the
     whole trade (2026-10-12: Jared Goff, a Seahawk by then, hidden in a saved Lions
     draft). He's dropped, and named.
   - picks are saved against the draft year they were picked under (pickBase). When the
     league's next draft moves on, each pick keeps naming the same draft, and one whose
     draft has already been held is dropped. Drafts saved before pickBase existed meant
     the draft that was next when they were built; with no way to know which, they're
     taken to mean the current one.
   Returns lines describing what changed. */
function tradeReconcile() {
  const notes = [];
  for (const side of ["a", "b"]) {
    if (!TRADE[side]) continue;
    const key = side + "Players";
    const roster = rosterOf(TRADE[side]);
    const gone = TRADE[key].filter((id) => !roster.some((p) => p.id === id));
    if (!gone.length) continue;
    TRADE[key] = TRADE[key].filter((id) => !gone.includes(id));
    for (const id of gone) notes.push(`${whereNow(id) || "a player who's left the league"} (was on the ${team(TRADE[side]).nick} side)`);
  }
  const next = DATA.nextDraftYear;
  let changed = notes.length > 0;
  if (next) {
    const base = TRADE.pickBase || next;
    if (base !== next) {
      for (const key of ["aPicks", "bPicks"]) {
        const kept = [];
        for (const p of TRADE[key]) {
          const offset = base + p[2] - next;
          if (offset >= 0 && offset <= 2) kept.push([p[0], p[1], offset]);
          else notes.push(`the ${base + p[2]} ${p[0]}${["st","nd","rd"][p[0]-1] || "th"}-round pick (${offset < 0 ? "that draft has been held" : "too far out to trade"})`);
        }
        TRADE[key] = kept;
      }
    }
    if (TRADE.pickBase !== next) { TRADE.pickBase = next; changed = true; }
  }
  if (changed) { TRADE.code = null; tradeSaveState(); }
  return notes;
}

function rosterOf(teamId) { return (DATA.rosters && DATA.rosters[String(teamId)]) || []; }

function sideTotal(teamId, playerIds, picks) {
  const roster = rosterOf(teamId);
  const pv = playerIds.reduce((sum, id) => sum + ((roster.find((p) => p.id === id) || {}).value || 0), 0);
  return pv + picks.reduce((sum, p) => sum + pickValue(p[0], p[1], p[2]), 0);
}

